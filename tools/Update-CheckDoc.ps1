#Requires -Version 7.2
<#
.SYNOPSIS
    Generates docs/checks.md from the check metadata (single source of truth).
    tests/Unit/Docs.Tests.ps1 fails when the committed file is out of date.

.EXAMPLE
    ./tools/Update-CheckDoc.ps1
#>
[CmdletBinding()]
param(
    [string]$Path = (Join-Path $PSScriptRoot '../docs/checks.md')
)

$ErrorActionPreference = 'Stop'
Import-Module (Join-Path $PSScriptRoot '../adoscope.psd1') -Force
$checks = & (Get-Module adoscope) { Import-AdoScopeCheck -Path $script:CheckRoot } | Sort-Object Id
$endpoints = & (Get-Module adoscope) { $script:CollectionSource }
$severityRank = @{ Critical = 0; High = 1; Medium = 2; Low = 3; Info = 4 }

$unmapped = @($checks.Requires | Sort-Object -Unique | Where-Object { -not $endpoints.Contains($_) })
if ($unmapped) { throw "Add the endpoint of collection(s) $($unmapped -join ', ') to `$script:CollectionSource in src/Private/Core/Get-AdoScopeContext.ps1." }

$lines = [System.Collections.Generic.List[string]]::new()
$lines.Add('# adoscope checks')
$lines.Add('')
$lines.Add('<!-- Generated by tools/Update-CheckDoc.ps1 from check metadata. Do not edit by hand. -->')
$lines.Add('')
$lines.Add("$($checks.Count) checks. Severities and parameters can be overridden in ``adoscope.config.psd1``.")
$lines.Add('')
$lines.Add('Standards: [OWASP Top 10 CI/CD Security Risks](https://owasp.org/www-project-top-10-ci-cd-security-risks/). Hygiene, cost and reliability checks are not security risks and map to none.')
$lines.Add('')
$lines.Add('| ID | Severity | Category | Title | OWASP CI/CD |')
$lines.Add('|---|---|---|---|---|')
foreach ($c in $checks | Sort-Object { $severityRank[$_.Severity] }, Id) {
    $lines.Add("| [$($c.Id)](#$($c.Id.ToLowerInvariant())) | $($c.Severity) | $($c.Category) | $($c.Title) | $(@($c.Standards) -join ', ') |")
}
foreach ($c in $checks) {
    $lines.Add('')
    $lines.Add("## $($c.Id)")
    $lines.Add('')
    $lines.Add("**$($c.Title)**: $($c.Severity), $($c.Category)")
    $lines.Add('')
    $lines.Add("**Why it matters.** $($c.Rationale)")
    $lines.Add('')
    $lines.Add("**How to fix.** $($c.Remediation)")
    $lines.Add('')
    $lines.Add("**Data.** $(($c.Requires | ForEach-Object { "$_ ($($endpoints[$_]))" }) -join '; ')")
    if (@($c.Standards).Count) {
        $lines.Add('')
        $lines.Add("**Standards.** OWASP Top 10 CI/CD: $(@($c.Standards) -join ', ')")
    }
    if ($c.Parameters.Count) {
        $lines.Add('')
        $lines.Add('**Parameters** (defaults):')
        $lines.Add('')
        foreach ($name in $c.Parameters.Keys | Sort-Object) {
            $value = $c.Parameters[$name]
            $shown = if ($value -is [array]) { "@($(($value | ForEach-Object { "'$_'" }) -join ', '))" } elseif ($value -is [hashtable]) { '@{}' } else { $value }
            $lines.Add("- ``$name`` = ``$shown``")
        }
    }
}
$markdown = ($lines -join "`n") + "`n"
New-Item -ItemType Directory -Force -Path (Split-Path $Path) | Out-Null
Set-Content -LiteralPath $Path -Value $markdown -NoNewline -Encoding utf8NoBOM
